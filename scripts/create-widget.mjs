/**
 * 脚手架：`npm run create:widget -- <id> [--name "Pretty Name"] [--out <dir>]`
 *
 * 生成一个**能直接跑**的组件目录：清单、入口、样式、图标、以及一份 SDK。
 * 生成的组件不是"空壳 + TODO"，而是一个真的会跳秒、属性面板里还有一个能改的
 * 标题的卡片 —— 拖进窗口、投放到桌面就能看见东西在动，作者改的时候有对照物。
 *
 * # 为什么要有这个
 *
 * 从零写一个组件要记住的东西不少：清单字段有哪些、`entry` 指哪儿、权限怎么
 * 声明、`ready` 什么时候发、心跳为什么不能用 `setInterval`。这些在
 * WIDGET_SPEC 里都写着，但"照文档拼一遍"和"跑起来再改"是两种心情。
 *
 * # 为什么 id 必须有分隔符
 *
 * 清单 id 的规则是 `a.b` 或 `a-b` 这样的多段形式（`manifest.ts` 的 `ID_RE`）。
 * 单段 id（`hello`）会被平台拒掉 —— 而拒的地方离"我刚生成完"很远，所以
 * 这里提前挡住，并且直接告诉你该写成什么。
 */
import { copyFileSync, existsSync, mkdirSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const ID_RE = /^[a-z0-9]+(?:[.-][a-z0-9]+)+$/;

function parseArgs(argv) {
  const args = { id: null, name: null, out: null, layer: "desktop", permissions: [], interactive: false };
  const rest = [];
  for (let index = 0; index < argv.length; index += 1) {
    const token = argv[index];
    if (token === "--name") args.name = argv[++index];
    else if (token === "--out") args.out = argv[++index];
    else if (token === "--layer") args.layer = argv[++index];
    else if (token === "--permissions") {
      args.permissions = String(argv[++index] ?? "")
        .split(",")
        .map((value) => value.trim())
        .filter(Boolean);
    } else if (token === "--interactive") args.interactive = true;
    else if (token.startsWith("--")) throw new Error(`unknown option ${token}`);
    else rest.push(token);
  }
  args.id = rest[0] ?? null;
  return args;
}

function usage(message) {
  if (message) console.error(`\n  ${message}\n`);
  console.error("  用法：npm run create:widget -- <id> [选项]\n");
  console.error("    --name <名字>          显示名，默认取 id 的最后一段并首字母大写");
  console.error("    --out <目录>           生成到哪儿，默认 public/widgets/<id>");
  console.error("    --layer desktop|top    贴桌面还是置顶，默认 desktop");
  console.error("    --permissions a,b      要申请的权限，逗号分隔");
  console.error("    --interactive          需要键盘输入时加（窗口会可激活）\n");
  console.error("  例子：npm run create:widget -- demo.weather --name \"Weather\" --permissions network\n");
  process.exit(1);
}

const args = (() => {
  try {
    return parseArgs(process.argv.slice(2));
  } catch (error) {
    usage(error.message);
  }
})();

if (!args.id) usage("缺少组件 id");
if (!ID_RE.test(args.id)) {
  const suggestion = args.id.includes(".") || args.id.includes("-") ? args.id : `demo.${args.id}`;
  usage(`id "${args.id}" 不合规 —— 清单 id 必须是两段以上，例如 ${suggestion}`);
}
if (args.layer !== "desktop" && args.layer !== "top") usage("--layer 只能是 desktop 或 top");

const prettyName =
  args.name ||
  (() => {
    const last = args.id.split(/[.-]/).pop() || args.id;
    return last.charAt(0).toUpperCase() + last.slice(1);
  })();

const target = args.out ? resolve(process.cwd(), args.out) : join(root, "public", "widgets", args.id);

if (existsSync(target) && readdirSync(target).length > 0) {
  usage(`${target} 已经存在而且不是空目录 —— 换一个 id，或者先用 --out 指到别处`);
}

// ---------------------------------------------------------------------------
// 文件内容
// ---------------------------------------------------------------------------

const manifest = {
  id: args.id,
  name: prettyName,
  version: "0.1.0",
  description: "A widget generated by create-lattice-widget",
  author: "",
  entry: "index.html",
  icon: "icon.svg",
  size: { w: 240, h: 140, minW: 160, minH: 96 },
  layer: args.layer,
  permissions: args.permissions,
  // 带一个可配置项出厂：属性面板一打开就有东西可调，作者能顺着它加第二个。
  // 空清单的话，"配置怎么接"要等到他自己写完才发现没接对。
  config: [
    {
      key: "caption",
      type: "text",
      label: "Caption",
      default: "",
      placeholder: prettyName,
      maxLength: 40,
      help: "The small line above the number. Empty falls back to the widget name.",
    },
  ],
  sdk: "^0.1",
};
if (args.interactive) manifest.interactive = true;

const html = `<!doctype html>
<html lang="en">
  <head>
    <meta charset="UTF-8" />
    <title>${prettyName}</title>
    <link rel="stylesheet" href="style.css" />
  </head>
  <body>
    <main class="card">
      <p class="card-label" id="label">${prettyName}</p>
      <p class="card-value" id="value">--:--:--</p>
    </main>
    <script type="module" src="widget.js"></script>
  </body>
</html>
`;

const script = `/**
 * ${prettyName} —— 由 create-lattice-widget 生成
 *
 * 这个卡片现在做两件事：每秒跳一次秒数，以及读清单里的 config。
 * 它同时证明了四条链路都通了 —— SDK 连上了宿主、心跳挂在平台的调度器上、
 * 主题令牌应用到了 CSS 变量、属性面板改了值卡片当场跟着变。
 *
 * 接下来通常这么改：
 *   1. 想让你调的东西（开关、数字、日期、下拉）写进 manifest.json 的 "config"，
 *      这里已经有一个 "caption"；属性面板会按类型渲染表单，你不用写 UI
 *   2. 要存数据用 lattice.storage（记得在清单里申请 "storage"）
 *   3. 要联网走 lattice.network.fetch（要 "network"，而且得列 hosts）
 *
 * 心跳**不要**换成 setInterval：窗口收起来 / 暂停全部时，平台的时间轴会停，
 * 自己开的定时器不会 —— 用户看不见的组件不该占 CPU。
 */
import { createLattice } from "./lattice.js";

const lattice = createLattice();
const labelEl = document.getElementById("label");
const valueEl = document.getElementById("value");

const pad = (value) => String(value).padStart(2, "0");

function render() {
  const now = new Date();
  const caption = lattice.config.caption;
  labelEl.textContent = caption ? String(caption) : ${JSON.stringify(prettyName)};
  valueEl.textContent = pad(now.getHours()) + ":" + pad(now.getMinutes()) + ":" + pad(now.getSeconds());
}

// ready 之后主题和配置已经各应用过一次，所以第一帧的颜色和文案就是对的
await lattice.ready;
render();

// 属性面板改了值：就地重画。别 reload —— 那会把组件里的状态（滚动位置、
// 还没提交的输入）全清掉，用户只是改了一个字
lattice.on("config", render);

await lattice.schedule.every(1000, render);
`;

const css = `/*
 * 组件只认令牌，不写死颜色 —— 底板一变浅，平台会把令牌整体翻一遍，
 * 写死的颜色不会跟着翻。短名（--fg / --muted / --accent）由 SDK 设好，
 * 长名（--lattice-text 之类）是平台的正式契约，两个都能用。
 */
:root {
  --fg: #1c1c1a;
  --muted: #6a6a63;
  --accent: #0f6e56;
  --border: rgba(0, 0, 0, 0.09);
  --radius: 10px;
  --font: "Segoe UI Variable Text", "Segoe UI", "Microsoft YaHei UI", system-ui, sans-serif;
}

* {
  box-sizing: border-box;
}

html,
body {
  height: 100%;
  margin: 0;
}

body {
  /* 必须透明：底板是宿主画的，组件自己刷一层背景会把磨砂层盖掉 */
  background: transparent;
  color: var(--fg);
  font-family: var(--font);
}

.card {
  display: flex;
  flex-direction: column;
  align-items: center;
  justify-content: center;
  gap: 4px;
  height: 100%;
  /* 顶部留 34px：窗饰（拖动 / 层级 / 别针 / 收回 / 重载）浮在右上角 */
  padding: 34px 14px 14px;
  border: 1px solid var(--border);
  border-radius: var(--radius);
}

.card-label {
  margin: 0;
  font-size: 11px;
  letter-spacing: 0.04em;
  text-transform: uppercase;
  color: var(--muted);
}

.card-value {
  margin: 0;
  font-size: 30px;
  font-weight: 600;
  font-variant-numeric: tabular-nums;
  letter-spacing: -0.02em;
}
`;

const icon = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 16 16" fill="none" stroke="#000" stroke-width="1.4" stroke-linecap="round" stroke-linejoin="round">
  <rect x="2.4" y="3.4" width="11.2" height="9.2" rx="2" />
  <path d="M2.4 6.4h11.2" />
</svg>
`;

const readme = `# ${prettyName}

A Lattice widget generated by \`create-lattice-widget\`.

\`\`\`
manifest.json   清单元数据：尺寸、层级、权限、可配置项
index.html      入口。组件就是一个普通网页
widget.js       逻辑。用 ./lattice.js（SDK）跟平台说话
style.css       样式。只用 --lattice-* 令牌，不写死颜色
icon.svg        组件库 / 画布标题条上的图标（单色，会被当遮罩用）
lattice.js      SDK 的副本 —— 跟着组件分发，不需要构建
\`\`\`

## Run it

\`\`\`bash
npm run widgets:index     # 让平台发现这个包（改完清单也要跑）
npm run dev               # 浏览器里看：http://localhost:1420
\`\`\`

在组件库里安装它，拖到画布上，然后"投放到桌面"。

## Notes

- 改文件存盘，桌面上的卡片会自己重载 —— 不用重启
- 想让你调的东西写进 \`manifest.json\` 的 \`config\`（\`text\` / \`number\` / \`toggle\` /
  \`select\` / \`date\`），属性面板会按类型渲染表单，你不用自己写设置界面
- 组件要接键盘输入（输入框、快捷键）才加 \`"interactive": true\`；
  不加的话窗口不可激活，点了也拿不到焦点
- 组件跑在 \`sandbox="allow-scripts"\` 的 iframe 里：没有 \`localStorage\`，
  也没有直接联网，能力一律走 SDK
- 两个跑在真实场景里的范例：\`public/widgets/lattice.weather\`（联网 + 缓存 +
  网络断了还能看）和 \`public/widgets/lattice.focus\`（多实例共享状态）
- 规格全文见仓库的 \`docs/WIDGET_SPEC.md\`
`;

// ---------------------------------------------------------------------------
// 落盘
// ---------------------------------------------------------------------------

mkdirSync(target, { recursive: true });
writeFileSync(join(target, "manifest.json"), `${JSON.stringify(manifest, null, 2)}\n`);
writeFileSync(join(target, "index.html"), html);
writeFileSync(join(target, "widget.js"), script);
writeFileSync(join(target, "style.css"), css);
writeFileSync(join(target, "icon.svg"), icon);
writeFileSync(join(target, "README.md"), readme);

// SDK 直接从源拷一份：和 examples 里那些保持同一版（`npm run test:sdk` 盯着漂移）
for (const file of ["lattice.js", "lattice.d.ts"]) {
  copyFileSync(join(root, "packages", "sdk", file), join(target, file));
}

const relative = target.startsWith(root) ? target.slice(root.length + 1) : target;
console.log(`\n  已生成 ${args.id} → ${relative}\n`);
console.log("  文件：manifest.json  index.html  widget.js  style.css  icon.svg  README.md");
console.log("        lattice.js  lattice.d.ts（SDK 副本）\n");
if (target.startsWith(join(root, "public", "widgets"))) {
  console.log("  下一步：npm run widgets:index  →  npm run dev\n");
} else {
  console.log("  下一步：把这个目录拖进 Lattice 窗口就能安装\n");
}
